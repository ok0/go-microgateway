const plannedDir = "." + "ens" + "emble"

var docSkipDirs = []string{".git", ".docs", "bin", "testdata", "vendor", plannedDir}

func TestDocComments(t *testing.T) {
	cases := []struct {
		name, file, src, want string
	}{
		{"uncommented func", "x/x.go", "package x\n\nfunc Foo() {}\n", "missing doc comment"},
		{"wrong start", "x/x.go", "package x\n\n// Does X.\nfunc Foo() {}\n", "doc comment does not start with Foo"},
		{"type with article", "x/x.go", "package x\n\n// A Foo is a thing.\ntype Foo struct{}\n", ""},
		{"method on unexported type", "x/x.go", "package x\n\ntype t struct{}\n\nfunc (t) Exported() {}\n", ""},
		{"method on exported type", "x/x.go", "package x\n\n// T is a thing.\ntype T struct{}\n\nfunc (t *T) Run() {}\n", "missing doc comment"},
		{"grouped const with block comment", "x/x.go", "package x\n\n// Limits of the thing.\nconst (\n\tA = 1\n\tB = 2\n)\n", ""},
		{"grouped var without any", "x/x.go", "package x\n\nvar (\n\tB = 2\n)\n", "missing doc comment"},
		{"generated file", "x/gen.go", "// Code generated by tool. DO NOT EDIT.\n\npackage x\n\nfunc Foo() {}\n", ""},
		{"test file", "x/x_test.go", "package x\n\nfunc Foo() {}\n", ""},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got, err := DocComments(c.file, []byte(c.src))
			if err != nil {
				t.Fatal(err)
			}
			if c.want == "" {
				if len(got) != 0 {
					t.Errorf("DocComments = %+v, want no findings", got)
				}
				return
			}
			if len(got) != 1 || got[0].Pattern != c.want {
				t.Errorf("DocComments = %+v, want one finding %q", got, c.want)
			}
		})
	}
}

func TestPackageComment(t *testing.T) {
	cases := []struct {
		name  string
		files map[string]string
		want  bool
	}{
		{"no comment", map[string]string{"x/a.go": "package x\n"}, true},
		{"package comment", map[string]string{"x/a.go": "// Package x does things.\npackage x\n"}, false},
		{"comment without package name", map[string]string{"x/a.go": "// x does things.\npackage x\n"}, true},
		{"main with any comment", map[string]string{"cmd/a.go": "// Command tool runs.\npackage main\n"}, false},
		{"test file ignored", map[string]string{"x/a.go": "// Package x does things.\npackage x\n", "x/a_test.go": "package x\n"}, false},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			files := map[string][]byte{}
			for name, src := range c.files {
				files[name] = []byte(src)
			}
			got := PackageComment(files)
			if (len(got) != 0) != c.want {
				t.Errorf("PackageComment = %+v, want a finding: %v", got, c.want)
			}
		})
	}
}

func TestExportedDocComments(t *testing.T) {
	root := repoRoot(t)
	groups, err := docGroups(root)
	if err != nil {
		t.Fatal(err)
	}
	if n := scannedDirs(groups); n < 40 {
		t.Fatalf("scanned %d directories with Go files, want at least 40", n)
	}
	problems, err := docProblems(root)
	if err != nil {
		t.Fatal(err)
	}
	for _, p := range problems {
		t.Error(p)
	}
}

func TestExportedDocCommentsCatchesTempFile(t *testing.T) {
	dir := t.TempDir()
	writeTree(t, dir, map[string]string{"p/p.go": "package p\n\nfunc Exported() {}\n"})
	problems, err := docProblems(dir)
	if err != nil {
		t.Fatal(err)
	}
	joined := strings.Join(problems, "\n")
	if len(problems) < 2 || !strings.Contains(joined, "package comment") || !strings.Contains(joined, "Exported") {
		t.Errorf("problems %q, want the missing package comment and Exported", problems)
	}
}

// docGroups reads the Go files under root, skipping the directories that hold no repository source, and groups them by directory. Keys are slash-separated paths relative to root.
func docGroups(root string) (map[string]map[string][]byte, error) {
	groups := map[string]map[string][]byte{}
	err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if p != root && slices.Contains(docSkipDirs, d.Name()) {
				return filepath.SkipDir
			}
			return nil
		}
		if filepath.Ext(p) != ".go" {
			return nil
		}
		src, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(root, p)
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(rel)
		dir := filepath.ToSlash(filepath.Dir(rel))
		if groups[dir] == nil {
			groups[dir] = map[string][]byte{}
		}
		groups[dir][rel] = src
		return nil
	})
	return groups, err
}

// docProblems runs DocComments on every non-test file under root and PackageComment on every directory, and returns the findings as "path:line: message" strings in directory and file order.
func docProblems(root string) ([]string, error) {
	groups, err := docGroups(root)
	if err != nil {
		return nil, err
	}
	dirs := make([]string, 0, len(groups))
	for dir := range groups {
		dirs = append(dirs, dir)
	}
	sort.Strings(dirs)
	var problems []string
	for _, dir := range dirs {
		files := groups[dir]
		names := make([]string, 0, len(files))
		for name := range files {
			names = append(names, name)
		}
		sort.Strings(names)
		for _, name := range names {
			findings, err := DocComments(name, files[name])
			if err != nil {
				return nil, err
			}
			problems = append(problems, formatFindings(findings)...)
		}
		problems = append(problems, formatFindings(PackageComment(files))...)
	}
	return problems, nil
}

// scannedDirs counts the directories that hold at least one non-test Go file.
func scannedDirs(groups map[string]map[string][]byte) int {
	n := 0
	for _, files := range groups {
		for name := range files {
			if !strings.HasSuffix(name, "_test.go") {
				n++
				break
			}
		}
	}
	return n
}

func formatFindings(findings []Finding) []string {
	out := make([]string, 0, len(findings))
	for _, f := range findings {
		msg := f.Pattern
		if f.Text != "" {
			msg = f.Text + ": " + f.Pattern
		}
		out = append(out, fmt.Sprintf("%s:%d: %s", f.Path, f.Line, msg))
	}
	return out
}
