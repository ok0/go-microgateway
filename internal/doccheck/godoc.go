package doccheck

import (
	"go/ast"
	"go/parser"
	"go/token"
	"path"
	"regexp"
	"sort"
	"strings"
)

var generatedRE = regexp.MustCompile(`^// Code generated .* DO NOT EDIT\.$`)

// DocComments reports the exported declarations of one Go source file that have no doc comment, or whose doc comment does not start with the declared name, following the revive exported rule. file is the path reported in each Finding. Test files and files generated by a tool yield no findings.
func DocComments(file string, src []byte) ([]Finding, error) {
	if strings.HasSuffix(file, "_test.go") {
		return nil, nil
	}
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, file, src, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	if isGenerated(f) {
		return nil, nil
	}
	var out []Finding
	check := func(id *ast.Ident, doc *ast.CommentGroup, articles bool) {
		pattern := ""
		switch {
		case doc == nil:
			pattern = "missing doc comment"
		case !startsWithName(doc.Text(), id.Name, articles):
			pattern = "doc comment does not start with " + id.Name
		default:
			return
		}
		out = append(out, Finding{Path: file, Line: fset.Position(id.Pos()).Line, Text: id.Name, Pattern: pattern})
	}
	for _, decl := range f.Decls {
		switch d := decl.(type) {
		case *ast.FuncDecl:
			if !d.Name.IsExported() {
				continue
			}
			if d.Recv != nil && !ast.IsExported(receiverTypeName(d.Recv.List[0].Type)) {
				continue
			}
			check(d.Name, d.Doc, false)
		case *ast.GenDecl:
			switch d.Tok {
			case token.TYPE:
				for _, spec := range d.Specs {
					ts, ok := spec.(*ast.TypeSpec)
					if !ok || !ts.Name.IsExported() {
						continue
					}
					doc := ts.Doc
					if doc == nil {
						doc = d.Doc
					}
					check(ts.Name, doc, true)
				}
			case token.CONST, token.VAR:
				grouped := d.Lparen.IsValid()
				for _, spec := range d.Specs {
					vs, ok := spec.(*ast.ValueSpec)
					if !ok {
						continue
					}
					id := firstExported(vs.Names)
					if id == nil {
						continue
					}
					doc := vs.Doc
					if doc == nil && !grouped {
						doc = d.Doc
					}
					if doc == nil && grouped && d.Doc != nil {
						continue
					}
					check(id, doc, false)
				}
			}
		}
	}
	return out, nil
}

// PackageComment reports the package doc comment problems of one directory. files maps each file path of the directory to its source; test files and generated files are ignored. The package comment must exist in at least one file and, for a package other than main, the first package comment in file name order must start with "Package <name> ". The Path of each finding is the directory.
func PackageComment(files map[string][]byte) []Finding {
	var names []string
	for name := range files {
		if strings.HasSuffix(name, ".go") && !strings.HasSuffix(name, "_test.go") {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	if len(names) == 0 {
		return nil
	}
	dir := path.Dir(names[0])
	fset := token.NewFileSet()
	var out []Finding
	pkg := ""
	var first *ast.CommentGroup
	for _, name := range names {
		f, err := parser.ParseFile(fset, name, files[name], parser.ParseComments)
		if err != nil {
			out = append(out, Finding{Path: name, Text: err.Error(), Pattern: "unparsable Go file"})
			continue
		}
		if isGenerated(f) {
			continue
		}
		if pkg == "" {
			pkg = f.Name.Name
		}
		if first == nil && f.Doc != nil {
			first = f.Doc
		}
	}
	if pkg == "" {
		return out
	}
	switch {
	case first == nil:
		out = append(out, Finding{Path: dir, Pattern: "missing package comment"})
	case pkg != "main" && !strings.HasPrefix(first.Text(), "Package "+pkg+" "):
		out = append(out, Finding{Path: dir, Pattern: "package comment does not start with Package " + pkg})
	}
	return out
}

func isGenerated(f *ast.File) bool {
	for _, cg := range f.Comments {
		if cg.Pos() >= f.Package {
			break
		}
		for _, c := range cg.List {
			if generatedRE.MatchString(c.Text) {
				return true
			}
		}
	}
	return false
}

func startsWithName(text, name string, articles bool) bool {
	if strings.HasPrefix(text, name+" ") {
		return true
	}
	if !articles {
		return false
	}
	for _, article := range []string{"A ", "An ", "The "} {
		if strings.HasPrefix(text, article+name+" ") {
			return true
		}
	}
	return false
}

func firstExported(names []*ast.Ident) *ast.Ident {
	for _, n := range names {
		if n.IsExported() {
			return n
		}
	}
	return nil
}

func receiverTypeName(e ast.Expr) string {
	for {
		switch t := e.(type) {
		case *ast.StarExpr:
			e = t.X
		case *ast.IndexExpr:
			e = t.X
		case *ast.IndexListExpr:
			e = t.X
		case *ast.ParenExpr:
			e = t.X
		case *ast.Ident:
			return t.Name
		default:
			return ""
		}
	}
}
