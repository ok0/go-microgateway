func hasPattern(found []Finding, label string) bool {
	for _, f := range found {
		if f.Pattern == label {
			return true
		}
	}
	return false
}

func TestCopiedSource(t *testing.T) {
	cases := []struct {
		name, path, src, want string
	}{
		{"go copyright header", "x/a.go", "// Copyright 2014 The Go " + "Authors. All rights reserved.\n", "Go copyright notice"},
		{"bsd governance line", "x/b.txt", "// Use of this source code is governed by a BSD-styl" + "e license.\n", "BSD governance notice"},
		{"bundle marker", "x/c.go", "// Code generated by golang.org/x/tools/cmd/" + "bundle. DO NOT EDIT.\n", "bundler output"},
		{"http2 package", "x/x.go", "pack" + "age http2\n", "copied net/http package"},
		{"hpack package", "y/y.go", "pack" + "age hpack\n", "copied net/http package"},
		{"vendor path", "vendor/golang.org/x/net/a.go", "", "vendor directory"},
		{"h2server path", "internal/h2server/server.go", "", "copied HTTP/2 server directory"},
		{"patents file", "internal/h2server/PATENTS", "", "patent grant file"},
		{"mit grant line", "x/mit.txt", "Permission is hereby " + "granted, free of charge\n", "MIT grant"},
		{"apache header line", "x/h.go", "// Licensed under the " + "Apache License, Version 2.0\n", "Apache header"},
		{"spdx identifier line", "x/s.go", "// SPDX-" + "License-Identifier: MIT\n", "SPDX identifier"},
		{"gpl text line", "x/g.txt", "GNU " + "General Public License\n", "GPL text"},
		{"mpl text line", "x/m.txt", "Mozilla " + "Public License 2.0\n", "MPL text"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got := CopiedSource(c.path, []byte(c.src))
			if !hasPattern(got, c.want) {
				t.Errorf("CopiedSource(%q) = %+v, want pattern %q", c.path, got, c.want)
			}
		})
	}
	negatives := []struct {
		name, path, src string
	}{
		{"package name in text file", "notes.txt", "pack" + "age http2\n"},
		{"unrelated package", "server/server.go", "pack" + "age server\n"},
		{"similar directory name", "internal/h2serverx/a.go", ""},
		{"license identifier in readme", "README.md", "Apache-2.0"},
	}
	for _, c := range negatives {
		t.Run(c.name, func(t *testing.T) {
			if got := CopiedSource(c.path, []byte(c.src)); len(got) != 0 {
				t.Errorf("CopiedSource(%q) = %+v, want no findings", c.path, got)
			}
		})
	}
}

func TestCopiedSourceOwnFiles(t *testing.T) {
	for _, name := range []string{"copied.go", "copied_test.go"} {
		src, err := os.ReadFile(name)
		if err != nil {
			t.Fatal(err)
		}
		if got := CopiedSource(name, src); len(got) != 0 {
			t.Errorf("%s: findings %+v", name, got)
		}
	}
}

func TestDirectRequires(t *testing.T) {
	src := "module example.com/m\n\ngo 1.27\n\n" +
		"require github.com/a/direct v1.0.0\n\n" +
		"require (\n" +
		"\tgithub.com/b/one v1.0.0\n" +
		"\tgithub.com/b/two v1.2.0 // direct note\n" +
		"\tgithub.com/b/ind v0.1.0 // indirect\n" +
		"\tgithub.com/b/ind2 v0.1.0 // indirect; reason\n" +
		"\t\"github.com/c/quoted\" v2.0.0\n" +
		"\t// comment line\n" +
		")\n"
	want := []string{"github.com/a/direct", "github.com/b/one", "github.com/b/two", "github.com/c/quoted"}
	if got := DirectRequires([]byte(src)); !reflect.DeepEqual(got, want) {
		t.Errorf("DirectRequires = %q, want %q", got, want)
	}
	root, err := Root()
	if err != nil {
		t.Fatal(err)
	}
	gomod, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		t.Fatal(err)
	}
	direct := DirectRequires(gomod)
	if !slices.Contains(direct, "github.com/fsnotify/fsnotify") {
		t.Errorf("repository direct requires %q lack github.com/fsnotify/fsnotify", direct)
	}
	if slices.Contains(direct, "golang.org/x/sys") {
		t.Errorf("repository direct requires %q include the indirect golang.org/x/sys", direct)
	}
}

func copiedProblems(root string) ([]string, error) {
	var problems []string
	err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(root, p)
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(rel)
		if d.IsDir() {
			if p != root {
				switch d.Name() {
				case ".git", "." + "ens" + "emble", ".docs":
					return filepath.SkipDir
				}
			}
			for _, f := range CopiedSource(rel, nil) {
				problems = append(problems, fmt.Sprintf("%s:%d: %s", f.Path, f.Line, f.Pattern))
			}
			return nil
		}
		if rel == "LICENSE" {
			return nil
		}
		src, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		for _, f := range CopiedSource(rel, src) {
			problems = append(problems, fmt.Sprintf("%s:%d: %s", f.Path, f.Line, f.Pattern))
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	for _, name := range []string{"go.mod", filepath.Join("redis", "go.mod")} {
		gomod, err := os.ReadFile(filepath.Join(root, name))
		if errors.Is(err, fs.ErrNotExist) {
			continue
		}
		if err != nil {
			return nil, err
		}
		if slices.Contains(DirectRequires(gomod), "golang.org/x/net") {
			problems = append(problems, fmt.Sprintf("%s: requires golang.org/x/net", filepath.ToSlash(name)))
		}
	}
	return problems, nil
}

func TestNoCopiedSource(t *testing.T) {
	root, err := Root()
	if err != nil {
		t.Fatal(err)
	}
	problems, err := copiedProblems(root)
	if err != nil {
		t.Fatal(err)
	}
	for _, p := range problems {
		t.Errorf("copied source: %s", p)
	}
}

func writeTree(t *testing.T, root string, files map[string]string) {
	t.Helper()
	for name, body := range files {
		p := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func hasProblemWithPrefix(problems []string, prefix string) bool {
	for _, p := range problems {
		if strings.HasPrefix(p, prefix) {
			return true
		}
	}
	return false
}

func TestNoCopiedSourceCatchesSeededTree(t *testing.T) {
	seeded := t.TempDir()
	writeTree(t, seeded, map[string]string{
		"go.mod":                      "module example.com/seeded\n\ngo 1.27\n\nrequire golang.org/x/net v0.1.0\n",
		"internal/h2server/server.go": "package server\n",
		"vendor/x/x.go":               "package x\n",
		"docs/x.md":                   "Permission is hereby " + "granted, free of charge\n",
		"sub/LICENSE":                 "Licensed under the " + "Apache License, Version 2.0\n",
	})
	problems, err := copiedProblems(seeded)
	if err != nil {
		t.Fatal(err)
	}
	if !hasProblemWithPrefix(problems, "docs/x.md:1: MIT grant") {
		t.Errorf("seeded tree problems %q lack the MIT grant in docs/x.md", problems)
	}
	if !hasProblemWithPrefix(problems, "sub/LICENSE:1: Apache header") {
		t.Errorf("seeded tree problems %q lack the Apache header in sub/LICENSE", problems)
	}
	if !hasProblemWithPrefix(problems, "internal/h2server:") {
		t.Errorf("seeded tree problems %q lack the internal/h2server path", problems)
	}
	if !hasProblemWithPrefix(problems, "vendor:") && !hasProblemWithPrefix(problems, "vendor/") {
		t.Errorf("seeded tree problems %q lack the vendor path", problems)
	}
	if !slices.Contains(problems, "go.mod: requires golang.org/x/net") {
		t.Errorf("seeded tree problems %q lack the golang.org/x/net require", problems)
	}

	clean := t.TempDir()
	writeTree(t, clean, map[string]string{
		"go.mod": "module example.com/clean\n\ngo 1.27\n",
		"a.go":   "package clean\n",
	})
	problems, err = copiedProblems(clean)
	if err != nil {
		t.Fatal(err)
	}
	if len(problems) != 0 {
		t.Errorf("clean tree problems %q, want none", problems)
	}
}
